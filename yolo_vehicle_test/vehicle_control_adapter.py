class ControlMode(str, Enum):
    """Operational mode of the vehicle control adapter."""
    MODE_OFFLINE_MOCK = "MODE_OFFLINE_MOCK"          # Default: Offline simulation, zero ROS 2/CAN transmission
    MODE_MONITOR = "MODE_MONITOR"                    # Passive listen-only to ROS 2 topics if available
    MODE_ACTUATION_GATE = "MODE_ACTUATION_GATE"      # Hardware live mode (Strictly locked by passkey)
    MODE_HARDWARE_BRIDGE = "MODE_HARDWARE_BRIDGE"    # Active ROS 2 DBW topic bridge (Publishes to /dbw/auto/*)


class SubsystemStatus(str, Enum):
    """Lifecycle and communication status of individual control subsystems."""
    REQUESTED = "REQUESTED"                          # Generated by perception decision engine
    PUBLISHED = "PUBLISHED"                          # Dispatched into ROS 2 transport queue
    RECEIVED = "RECEIVED"                            # Acknowledged by DBW supervisor node
    ACCEPTED = "ACCEPTED"                            # Validated against clamps, slew-rate & FSM state
    EXECUTED = "EXECUTED"                            # Confirmed by physical actuator / encoder feedback
    FEEDBACK_UNAVAILABLE = "FEEDBACK_UNAVAILABLE"    # Sensor feedback disconnected or offline mode
    FAULT = "FAULT"                                  # Subsystem error, limit exceeded, or watchdog failure


class FSMState(str, Enum):
    """DBW Supervisor Finite State Machine states."""
    IDLE = "IDLE"                                    # Deadman released / Standby / Neutral
    AUTOMODE = "AUTOMODE"                            # Autonomous control active
    FAULT = "FAULT"                                  # Emergency stop / Hardware fault / Watchdog bite


@dataclass
class SubsystemChannel:
    """Detailed state tracking for a single control channel."""
    name: str
    target_value: float = 0.0                        # Raw value requested by perception
    commanded_value: float = 0.0                     # Filtered / slew-limited value sent to DBW
    feedback_value: float = 0.0                      # Measured feedback from encoder / CCU
    status: SubsystemStatus = SubsystemStatus.REQUESTED
    last_request_time: float = 0.0
    last_publish_time: float = 0.0
    last_feedback_time: float = 0.0
    fault_reason: Optional[str] = None


@dataclass
class AdapterTelemetry:
    """Comprehensive snapshot of adapter telemetry for GUI and diagnostic consumption."""
    timestamp: float
    mode: ControlMode
    fsm_state: FSMState
    deadman_active: bool
    deadman_rate_hz: float
    perception_fresh: bool
    perception_age_ms: float
    last_decision_str: str
    steer: SubsystemChannel
    velocity: SubsystemChannel
    brake: SubsystemChannel
    simulated_modbus_reg3: int                       # Raw 16-bit register written to PLC
    simulated_modbus_reg0: int                       # Raw 16-bit register read from PLC
    simulated_can_tx_bytes: bytes                    # 8-byte frame sent to CCU (ID: 0x12280797)
    simulated_can_rx_bytes: bytes                    # 8-byte frame received from CCU (ID: 0x12910109)
    emergency_stop: bool
    is_safe: bool
    has_real_feedback: bool = False                  # True if feedback arrived from actual ROS 2 topics
    is_ros_connected: bool = False                   # True if connected to live ROS 2 Jazzy graph


class VehicleControlAdapter:
    """
    High-reliability control adapter bridging YOLO26n-seg perception decisions
    to the VIRYA DBW platform control interfaces.
    """

    # Physical and software constants from DBW reference
    STEER_LIMIT_DEG: float = 30.0                    # Software clamp in dbw.cpp line 3
    STEER_NOMINAL_AVOID_DEG: float = 10.0            # Obstacle avoidance turn magnitude
    STEER_SLEW_RATE_DEG_PER_SEC: float = 30.0        # Max physical steering rate (deg/s)
    
    VELOCITY_LIMIT_MPS: float = 2.5                  # Software clamp in dbw.cpp line 4
    VELOCITY_NOMINAL_FORWARD: float = 1.0            # Forward cruising speed (m/s)
    VELOCITY_CAUTION_PACE: float = 0.5               # Maneuvering / avoiding speed (m/s)
    VELOCITY_ACCEL_LIMIT_MPS2: float = 1.5           # Max longitudinal acceleration rate (m/s^2)
    
    CONTROL_LOOP_HZ: float = 20.0                    # Periodic control frequency (50 ms cycle)
    DEADMAN_TIMEOUT_SEC: float = 0.200               # DBW FSM deadman watchdog timeout (200 ms)
    SPEED_WATCHDOG_TIMEOUT_SEC: float = 0.150        # DBW speed watchdog timeout (150 ms)
    STEER_COUPLING_TIMEOUT_SEC: float = 0.120        # DBW steer-speed coupling timeout (120 ms)
    PERCEPTION_TIMEOUT_SEC: float = 0.300            # Adapter perception staleness timeout (300 ms)
    
    # CAN & Modbus Constants
    CAN_TX_ID: int = 0x12280797                      # Transmit CAN ID to CCU
    CAN_RX_ID: int = 0x12910109                      # Receive CAN ID from CCU
    MODBUS_IP: str = "192.168.0.5"
    MODBUS_PORT: int = 502
    MODBUS_STEER_WRITE_REG: int = 3                  # Register 3: Commanded steering
    MODBUS_STEER_READ_REG: int = 0                   # Register 0: Steering encoder feedback

    def __init__(
        self,
        mode: ControlMode = ControlMode.MODE_OFFLINE_MOCK,
        steer_slew_rate: float = STEER_SLEW_RATE_DEG_PER_SEC,
        control_loop_hz: float = CONTROL_LOOP_HZ,
        passkey: Optional[str] = None,
    ):
        self.mode = mode
        self.steer_slew_rate = steer_slew_rate
        self.control_loop_hz = control_loop_hz
        self.loop_period = 1.0 / control_loop_hz
        self.passkey = passkey

        # Subsystem tracking channels
        self.steer_channel = SubsystemChannel(name="steering")
        self.velocity_channel = SubsystemChannel(name="velocity")
        self.brake_channel = SubsystemChannel(name="brake")

        # FSM and Watchdog state
        self.fsm_state = FSMState.IDLE
        self.deadman_active = True
        self.deadman_counter = 0
        self.last_deadman_time = time.time()
        self.emergency_stop = False

        # Perception input state
        self.last_perception_time = 0.0
        self.last_decision_str = "NONE"
        self.perception_healthy = False

        # Simulated hardware states (for MODE_OFFLINE_MOCK)
        self.sim_actual_steer = 0.0
        self.sim_actual_velocity = 0.0
        self.sim_actual_brake = True
        self.sim_modbus_reg3 = 0
        self.sim_modbus_reg0 = 0
        self.sim_can_tx = bytes([0] * 8)
        self.sim_can_rx = bytes([0] * 8)

        # Real ROS 2 DBW Bridge State
        self.ros_node = None
        self.ros_spin_thread: Optional[threading.Thread] = None
        self.ros_spin_running = False
        self.pub_steer = None
        self.pub_vel = None
        self.pub_brake = None
        self.pub_deadman = None
        self.sub_steer_fb = None
        self.sub_vel_fb = None
        self.sub_status_fb = None
        self.real_steer_fb = 0.0
        self.real_vel_fb = 0.0
        self.real_fsm_state = FSMState.IDLE
        self.last_real_fb_time = 0.0
        self.has_real_feedback = False
        self.is_ros_connected = False

        # Thread management
        self.running = False
        self._thread: Optional[threading.Thread] = None
        self._lock = threading.Lock()

        # Hardware safety verification: prevent accidental actuation
        if self.mode in (ControlMode.MODE_ACTUATION_GATE, ControlMode.MODE_HARDWARE_BRIDGE):
            if self.passkey != "ACTUATE_VIRYA_CONFIRM":
                logger.warning("⚠️ Invalid or missing passkey for live hardware mode. Forcing MODE_OFFLINE_MOCK.")
                self.mode = ControlMode.MODE_OFFLINE_MOCK

        logger.info(f"Initialized VehicleControlAdapter in mode: {self.mode.value}")

    def _init_ros2_bridge(self) -> bool:
        """Initializes ROS 2 Jazzy node, publishers, and feedback subscribers."""
        if not ROS2_AVAILABLE:
            logger.warning("rclpy not available in environment. Running in offline fallback.")
            return False
        try:
            if not rclpy.ok():
                rclpy.init(args=None)
            self.ros_node = Node("multi_object_control_adapter")

            # Subscribers for actual vehicle hardware feedback
            self.sub_steer_fb = self.ros_node.create_subscription(
                Float64, "/dbw/feedback/current_steer", self._on_steer_feedback, 10
            )
            self.sub_vel_fb = self.ros_node.create_subscription(
                Float64, "/dbw/feedback/vehicle_speed", self._on_vel_feedback, 10
            )
            self.sub_status_fb = self.ros_node.create_subscription(
                Int32, "/dbw/feedback/status", self._on_status_feedback, 10
            )

            # Publishers for actuation (only in active bridge mode)
            if self.mode in (ControlMode.MODE_HARDWARE_BRIDGE, ControlMode.MODE_ACTUATION_GATE):
                self.pub_steer = self.ros_node.create_publisher(Float64, "/dbw/auto/cmd_steer", 10)
                self.pub_vel = self.ros_node.create_publisher(Float64, "/dbw/auto/cmd_vel", 10)
                self.pub_brake = self.ros_node.create_publisher(Bool, "/dbw/auto/brake", 10)
                self.pub_deadman = self.ros_node.create_publisher(String, "/dbw/deadman_switch", 10)
                logger.info("✅ ROS 2 DBW publishers connected: /dbw/auto/cmd_steer, /dbw/auto/cmd_vel, /dbw/auto/brake, /dbw/deadman_switch")

            self.is_ros_connected = True
            self.ros_spin_running = True
            self.ros_spin_thread = threading.Thread(target=self._ros_spin_loop, name="AdapterROSSpinThread", daemon=True)
            self.ros_spin_thread.start()
            logger.info("✅ ROS 2 background spin thread active.")
            return True
        except Exception as e:
            logger.error(f"❌ Failed to initialize ROS 2 DBW bridge: {e}")
            self.is_ros_connected = False
            return False

    def _ros_spin_loop(self):
        """Dedicated spin loop for ROS 2 callbacks."""
        while self.ros_spin_running and rclpy.ok():
            try:
                rclpy.spin_once(self.ros_node, timeout_sec=0.02)
            except Exception:
                break

    def _on_steer_feedback(self, msg: Any):
        with self._lock:
            self.real_steer_fb = float(msg.data)
            self.last_real_fb_time = time.time()

    def _on_vel_feedback(self, msg: Any):
        with self._lock:
            self.real_vel_fb = float(msg.data)
            self.last_real_fb_time = time.time()

    def _on_status_feedback(self, msg: Any):
        with self._lock:
            code = int(msg.data)
            # 0: IDLE, 1: JOYMODE, 2: TELEOPMODE, 3: AUTOMODE, 4: FAULT
            if code == 3:
                self.real_fsm_state = FSMState.AUTOMODE
            elif code == 4:
                self.real_fsm_state = FSMState.FAULT
            else:
                self.real_fsm_state = FSMState.IDLE
            self.last_real_fb_time = time.time()

    def start(self):
        """Starts the periodic background control loop (20 Hz) and optional ROS 2 bridge."""
        if self.running:
            return

        if self.mode in (ControlMode.MODE_HARDWARE_BRIDGE, ControlMode.MODE_ACTUATION_GATE, ControlMode.MODE_MONITOR):
            self._init_ros2_bridge()

        self.running = True
        self._thread = threading.Thread(target=self._control_loop_thread, name="DBWControlAdapterThread", daemon=True)
        self._thread.start()
        logger.info(f"🚀 Vehicle control loop started at {self.control_loop_hz} Hz")

    def stop(self):
        """Cleanly stops the control loop, terminates ROS 2 nodes, and forces neutral setpoints."""
        self.running = False
        if self._thread and self._thread.is_alive():
            self._thread.join(timeout=1.0)

        with self._lock:
            self._force_safe_neutral("Adapter stopped")
            # If live ROS 2 publishers were active, publish safe neutral before exit
            if self.is_ros_connected and self.pub_vel is not None and ROS2_AVAILABLE and rclpy.ok():
                try:
                    self.pub_steer.publish(Float64(data=0.0))
                    self.pub_vel.publish(Float64(data=0.0))
                    self.pub_brake.publish(Bool(data=True))
                except Exception:
                    pass

        # Terminate ROS 2 spin thread
        if self.ros_spin_running:
            self.ros_spin_running = False
            if self.ros_spin_thread and self.ros_spin_thread.is_alive():
                self.ros_spin_thread.join(timeout=0.5)

        if self.ros_node is not None and ROS2_AVAILABLE and rclpy.ok():
            try:
                self.ros_node.destroy_node()
            except Exception:
                pass
            self.ros_node = None
        self.is_ros_connected = False

        logger.info("🛑 Vehicle control adapter stopped cleanly.")

    def update_perception_decision(
        self,
        decision_obj: Any,
        is_camera_healthy: bool = True,
    ):
        """
        Thread-safe ingestion of high-level perception decisions from YOLO26n-seg.
        Maps decisions directly to steering, velocity, and brake setpoints.
        """
        now = time.time()
        with self._lock:
            self.last_perception_time = now

            if not is_camera_healthy or decision_obj is None:
                self.perception_healthy = False
                self.last_decision_str = "FAULT_CAMERA_OR_INPUT"
                self._map_decision_to_targets("UNKNOWN")
                return

            self.perception_healthy = True
            dec_val = getattr(decision_obj, "decision", decision_obj)
            if hasattr(dec_val, "value"):
                dec_val = dec_val.value
            dec_str = str(dec_val).upper()
            self.last_decision_str = dec_str

            self._map_decision_to_targets(dec_str)

    def _map_decision_to_targets(self, decision_str: str):
        """
        Authoritative mapping from decision string to physical setpoints.
        Steering sign convention:
          MOVE_LEFT  -> +10.0 deg (Left turn is POSITIVE)
          MOVE_RIGHT -> -10.0 deg (Right turn is NEGATIVE)
          STRAIGHT   ->  0.0 deg
        """
        now = time.time()

        if decision_str == "STOP":
            target_steer = 0.0
            target_vel = 0.0
            target_brake = 1.0  # Assert brake
        elif decision_str == "MOVE_LEFT":
            target_steer = self.STEER_NOMINAL_AVOID_DEG    # +10.0 deg (LEFT)
            target_vel = self.VELOCITY_CAUTION_PACE        # 0.5 m/s
            target_brake = 0.0
        elif decision_str == "MOVE_RIGHT":
            target_steer = -self.STEER_NOMINAL_AVOID_DEG   # -10.0 deg (RIGHT)
            target_vel = self.VELOCITY_CAUTION_PACE        # 0.5 m/s
            target_brake = 0.0
        elif decision_str == "SLOW_DOWN":
            target_steer = 0.0
            target_vel = self.VELOCITY_CAUTION_PACE        # 0.5 m/s
            target_brake = 0.0
        elif decision_str == "PATH_CLEAR":
            target_steer = 0.0
            target_vel = self.VELOCITY_NOMINAL_FORWARD     # 1.0 m/s
            target_brake = 0.0
        else:  # UNKNOWN or unrecognized
            target_steer = 0.0
            target_vel = 0.0
            target_brake = 1.0

        # Update steering channel target
        self.steer_channel.target_value = self.clamp_steering(target_steer)
        self.steer_channel.status = SubsystemStatus.REQUESTED
        self.steer_channel.last_request_time = now

        # Update velocity channel target
        self.velocity_channel.target_value = self.clamp_velocity(target_vel)
        self.velocity_channel.status = SubsystemStatus.REQUESTED
        self.velocity_channel.last_request_time = now

        # Update brake channel target
        self.brake_channel.target_value = target_brake
        self.brake_channel.status = SubsystemStatus.REQUESTED
        self.brake_channel.last_request_time = now

    def _control_loop_thread(self):
        """20 Hz Periodic execution loop maintaining watchdog heartbeats and actuator slew."""
        last_tick_time = time.time()

        while self.running:
            tick_start = time.time()
            dt = tick_start - last_tick_time
            last_tick_time = tick_start

            with self._lock:
                self._execute_control_cycle(dt)

            # Sleep precisely to maintain 20 Hz
            elapsed = time.time() - tick_start
            sleep_time = max(0.001, self.loop_period - elapsed)
            time.sleep(sleep_time)

    def _execute_control_cycle(self, dt: float):
        """Executes a single 20 Hz control cycle."""
        now = time.time()

        # 1. Check Perception Staleness Watchdog (> 300 ms)
        perception_age = now - self.last_perception_time if self.last_perception_time > 0 else 999.0
        if perception_age > self.PERCEPTION_TIMEOUT_SEC:
            self.perception_healthy = False
            # Force safety stop on stale perception
            self.steer_channel.target_value = 0.0
            self.velocity_channel.target_value = 0.0
            self.brake_channel.target_value = 1.0
            self.steer_channel.fault_reason = f"Perception stale ({perception_age*1000:.0f} ms > 300 ms)"
            self.velocity_channel.fault_reason = f"Perception stale ({perception_age*1000:.0f} ms > 300 ms)"

        # 2. Evaluate Deadman Switch & DBW FSM
        if self.deadman_active and not self.emergency_stop:
            self.fsm_state = FSMState.AUTOMODE
            self.deadman_counter += 1
            self.last_deadman_time = now
        else:
            self.fsm_state = FSMState.FAULT if self.emergency_stop else FSMState.IDLE
            # In IDLE or FAULT, DBW forces neutral and full brake
            self.steer_channel.target_value = 0.0
            self.velocity_channel.target_value = 0.0
            self.brake_channel.target_value = 1.0

        # 3. Apply Steering Slew Rate Limiter (Max 30 deg/s)
        max_steer_delta = self.steer_slew_rate * dt
        steer_diff = self.steer_channel.target_value - self.steer_channel.commanded_value
        if abs(steer_diff) <= max_steer_delta:
            self.steer_channel.commanded_value = self.steer_channel.target_value
        else:
            self.steer_channel.commanded_value += math.copysign(max_steer_delta, steer_diff)

        # Clamp commanded steering
        self.steer_channel.commanded_value = self.clamp_steering(self.steer_channel.commanded_value)

        # 4. Apply Longitudinal Acceleration Ramp
        max_vel_delta = self.VELOCITY_ACCEL_LIMIT_MPS2 * dt
        vel_diff = self.velocity_channel.target_value - self.velocity_channel.commanded_value
        if abs(vel_diff) <= max_vel_delta:
            self.velocity_channel.commanded_value = self.velocity_channel.target_value
        else:
            self.velocity_channel.commanded_value += math.copysign(max_vel_delta, vel_diff)

        # Clamp commanded velocity
        self.velocity_channel.commanded_value = self.clamp_velocity(self.velocity_channel.commanded_value)

        # 5. Evaluate Automatic Braking Interlocks
        # As in dbw.cpp line 373: brake is forced to 1 if velocity == 0 or emergency_stop
        if abs(self.velocity_channel.commanded_value) < 0.01 or self.emergency_stop:
            self.brake_channel.commanded_value = 1.0
        else:
            self.brake_channel.commanded_value = self.brake_channel.target_value

        # 6. Mode Execution: Dispatch or Simulate
        if self.mode == ControlMode.MODE_OFFLINE_MOCK:
            self._simulate_dbw_hardware(dt, now)
        elif self.mode == ControlMode.MODE_MONITOR:
            self._passive_monitor(now)
        elif self.mode in (ControlMode.MODE_ACTUATION_GATE, ControlMode.MODE_HARDWARE_BRIDGE):
            self._dispatch_hardware_actuation(now)

    def _simulate_dbw_hardware(self, dt: float, now: float):
        """
        Simulates DBW Node, PLC Modbus registers, and CCU CAN communication.
        Provides realistic actuator lag and feedback without transmitting physical signals.
        """
        # A. Modbus Register Encoding
        # Commanded steering is scaled x10 into Register 3
        steer_int = int(round(self.steer_channel.commanded_value * 10))
        if steer_int >= 0:
            self.sim_modbus_reg3 = steer_int & 0xFFFF
        else:
            self.sim_modbus_reg3 = ((1 << 16) + steer_int) & 0xFFFF

        # Simulated steering actuator response (first-order lag tau ~ 0.08 s)
        alpha_steer = 1.0 - math.exp(-dt / 0.08)
        self.sim_actual_steer += alpha_steer * (self.steer_channel.commanded_value - self.sim_actual_steer)

        # Feedback Register 0
        fb_steer_int = int(round(self.sim_actual_steer * 10))
        if fb_steer_int >= 0:
            self.sim_modbus_reg0 = fb_steer_int & 0xFFFF
        else:
            self.sim_modbus_reg0 = ((1 << 16) + fb_steer_int) & 0xFFFF

        # B. CAN Frame Encoding (ID: 0x12280797)
        # Byte 0: Drive mode (0x01 Forward, 0x03 Reverse, 0x00 Stop)
        cmd_v = self.velocity_channel.commanded_value
        mode_byte = 0x01 if cmd_v > 0.05 else (0x03 if cmd_v < -0.05 else 0x00)
        speed_cm_s = int(round(abs(cmd_v) * 100))
        lsb = speed_cm_s & 0xFF
        msb = (speed_cm_s >> 8) & 0xFF
        brake_byte = 0x64 if self.brake_channel.commanded_value > 0.5 else 0x00
        park_brake = 0x01 if self.emergency_stop else 0x00
        heartbeat = 0x01

        self.sim_can_tx = bytes([mode_byte, lsb, msb, brake_byte, park_brake, 0x00, 0x00, heartbeat])

        # Simulated vehicle speed response (inertial lag tau ~ 0.15 s)
        alpha_v = 1.0 - math.exp(-dt / 0.15)
        if self.brake_channel.commanded_value > 0.5:
            # Rapid deceleration under brake
            self.sim_actual_velocity = max(0.0, self.sim_actual_velocity - 4.0 * dt)
        else:
            self.sim_actual_velocity += alpha_v * (cmd_v - self.sim_actual_velocity)

        # Simulated CAN Feedback Frame (ID: 0x12910109)
        # Bytes 6 & 7: signed int16 ground speed in cm/s
        fb_speed_cm = int(round(self.sim_actual_velocity * 100))
        fb_lsb = fb_speed_cm & 0xFF
        fb_msb = (fb_speed_cm >> 8) & 0xFF
        self.sim_can_rx = bytes([0x00, 0x00, 0x00, 0x00, 0x00, 0x00, fb_lsb, fb_msb])

        # C. Update Channel Status
        self.has_real_feedback = False
        self.steer_channel.status = SubsystemStatus.ACCEPTED
        self.steer_channel.last_publish_time = now
        self.steer_channel.feedback_value = self.sim_actual_steer
        self.steer_channel.last_feedback_time = now

        self.velocity_channel.status = SubsystemStatus.ACCEPTED
        self.velocity_channel.last_publish_time = now
        self.velocity_channel.feedback_value = self.sim_actual_velocity
        self.velocity_channel.last_feedback_time = now

        self.brake_channel.status = SubsystemStatus.ACCEPTED
        self.brake_channel.last_publish_time = now
        self.brake_channel.feedback_value = 1.0 if self.sim_actual_velocity < 0.05 else self.brake_channel.commanded_value
        self.brake_channel.last_feedback_time = now

    def _passive_monitor(self, now: float):
        """Passive monitor mode: records status from actual ROS 2 topics without any transmission."""
        if self.is_ros_connected and (now - self.last_real_fb_time) < 0.5:
            self.has_real_feedback = True
            self.steer_channel.feedback_value = self.real_steer_fb
            self.velocity_channel.feedback_value = self.real_vel_fb
            self.steer_channel.status = SubsystemStatus.EXECUTED
            self.velocity_channel.status = SubsystemStatus.EXECUTED
            self.brake_channel.status = SubsystemStatus.EXECUTED
            self.fsm_state = self.real_fsm_state
        else:
            self.has_real_feedback = False
            self.steer_channel.status = SubsystemStatus.FEEDBACK_UNAVAILABLE
            self.velocity_channel.status = SubsystemStatus.FEEDBACK_UNAVAILABLE
            self.brake_channel.status = SubsystemStatus.FEEDBACK_UNAVAILABLE

    def _dispatch_hardware_actuation(self, now: float):
        """Actuation mode: Publishes to ROS 2 topics /dbw/auto/* and deadman at 20 Hz."""
        if not self.is_ros_connected or self.pub_vel is None:
            self.steer_channel.status = SubsystemStatus.FEEDBACK_UNAVAILABLE
            self.velocity_channel.status = SubsystemStatus.FEEDBACK_UNAVAILABLE
            self.brake_channel.status = SubsystemStatus.FEEDBACK_UNAVAILABLE
            return

        try:
            steer_val = float(self.steer_channel.commanded_value)
            vel_val = float(self.velocity_channel.commanded_value)
            brake_val = bool(self.brake_channel.commanded_value > 0.5)

            self.pub_steer.publish(Float64(data=steer_val))
            self.pub_vel.publish(Float64(data=vel_val))
            self.pub_brake.publish(Bool(data=brake_val))

            self.steer_channel.last_publish_time = now
            self.velocity_channel.last_publish_time = now
            self.brake_channel.last_publish_time = now

            if self.deadman_active and not self.emergency_stop:
                self.pub_deadman.publish(String(data="Auto"))

            if (now - self.last_real_fb_time) < 0.5:
                self.has_real_feedback = True
                self.steer_channel.feedback_value = self.real_steer_fb
                self.velocity_channel.feedback_value = self.real_vel_fb
                self.steer_channel.status = SubsystemStatus.EXECUTED
                self.velocity_channel.status = SubsystemStatus.EXECUTED
                self.brake_channel.status = SubsystemStatus.EXECUTED
                self.fsm_state = self.real_fsm_state
            else:
                self.has_real_feedback = False
                self.steer_channel.status = SubsystemStatus.PUBLISHED
                self.velocity_channel.status = SubsystemStatus.PUBLISHED
                self.brake_channel.status = SubsystemStatus.PUBLISHED

        except Exception as e:
            logger.error(f"ROS 2 publication failure: {e}")
            self.steer_channel.status = SubsystemStatus.FAULT
            self.velocity_channel.status = SubsystemStatus.FAULT

    def trigger_emergency_stop(self, reason: str = "User E-STOP requested"):
        """Emergency stop: locks brake, drops velocity to 0, transitions FSM to FAULT."""
        with self._lock:
            self.emergency_stop = True
            self.fsm_state = FSMState.FAULT
            self._force_safe_neutral(reason)
            logger.warning(f"🚨 EMERGENCY STOP TRIGGERED: {reason}")

    def reset_emergency_stop(self):
        """Resets emergency stop and restores IDLE/STANDBY state."""
        with self._lock:
            self.emergency_stop = False
            self.fsm_state = FSMState.IDLE
            self._force_safe_neutral("E-STOP Reset")
            logger.info("✅ Emergency stop reset. System in IDLE.")

    def set_deadman(self, active: bool):
        """Enables or disables deadman switch heartbeat."""
        with self._lock:
            self.deadman_active = active
            if not active:
                self.fsm_state = FSMState.IDLE
                self._force_safe_neutral("Deadman inactive")

    def _force_safe_neutral(self, reason: str):
        """Enforces zero velocity, centered steering, and engaged brake."""
        now = time.time()
        self.steer_channel.target_value = 0.0
        self.steer_channel.commanded_value = 0.0
        self.velocity_channel.target_value = 0.0
        self.velocity_channel.commanded_value = 0.0
        self.brake_channel.target_value = 1.0
        self.brake_channel.commanded_value = 1.0
        self.steer_channel.fault_reason = reason
        self.velocity_channel.fault_reason = reason

    @staticmethod
    def clamp_steering(angle_deg: float) -> float:
        """Clamps commanded steering angle to [-30.0, +30.0] degrees."""
        return max(-VehicleControlAdapter.STEER_LIMIT_DEG, min(VehicleControlAdapter.STEER_LIMIT_DEG, float(angle_deg)))

    @staticmethod
    def clamp_velocity(vel_mps: float) -> float:
        """Clamps commanded linear velocity to [-2.5, +2.5] m/s."""
        return max(-VehicleControlAdapter.VELOCITY_LIMIT_MPS, min(VehicleControlAdapter.VELOCITY_LIMIT_MPS, float(vel_mps)))

    def get_telemetry(self) -> AdapterTelemetry:
        """Returns an atomic thread-safe snapshot of all adapter telemetry."""
        now = time.time()
        with self._lock:
            p_age_ms = (now - self.last_perception_time) * 1000.0 if self.last_perception_time > 0 else 9999.0
            is_safe = (
                self.perception_healthy and
                not self.emergency_stop and
                p_age_ms <= (self.PERCEPTION_TIMEOUT_SEC * 1000.0)
            )

            # Copy subsystem channels to avoid concurrent mutation
            steer_copy = SubsystemChannel(
                name="steering",
                target_value=self.steer_channel.target_value,
                commanded_value=self.steer_channel.commanded_value,
                feedback_value=self.steer_channel.feedback_value,
                status=self.steer_channel.status,
                last_request_time=self.steer_channel.last_request_time,
                last_publish_time=self.steer_channel.last_publish_time,
                last_feedback_time=self.steer_channel.last_feedback_time,
                fault_reason=self.steer_channel.fault_reason,
            )

            vel_copy = SubsystemChannel(
                name="velocity",
                target_value=self.velocity_channel.target_value,
                commanded_value=self.velocity_channel.commanded_value,
                feedback_value=self.velocity_channel.feedback_value,
                status=self.velocity_channel.status,
                last_request_time=self.velocity_channel.last_request_time,
                last_publish_time=self.velocity_channel.last_publish_time,
                last_feedback_time=self.velocity_channel.last_feedback_time,
                fault_reason=self.velocity_channel.fault_reason,
            )

            brake_copy = SubsystemChannel(
                name="brake",
                target_value=self.brake_channel.target_value,
                commanded_value=self.brake_channel.commanded_value,
                feedback_value=self.brake_channel.feedback_value,
                status=self.brake_channel.status,
                last_request_time=self.brake_channel.last_request_time,
                last_publish_time=self.brake_channel.last_publish_time,
                last_feedback_time=self.brake_channel.last_feedback_time,
                fault_reason=self.brake_channel.fault_reason,
            )

            return AdapterTelemetry(
                timestamp=now,
                mode=self.mode,
                fsm_state=self.fsm_state,
                deadman_active=self.deadman_active,
                deadman_rate_hz=self.control_loop_hz if self.deadman_active else 0.0,
                perception_fresh=self.perception_healthy and (p_age_ms <= self.PERCEPTION_TIMEOUT_SEC * 1000.0),
                perception_age_ms=p_age_ms,
                last_decision_str=self.last_decision_str,
                steer=steer_copy,
                velocity=vel_copy,
                brake=brake_copy,
                simulated_modbus_reg3=self.sim_modbus_reg3,
                simulated_modbus_reg0=self.sim_modbus_reg0,
                simulated_can_tx_bytes=self.sim_can_tx,
                simulated_can_rx_bytes=self.sim_can_rx,
                emergency_stop=self.emergency_stop,
                is_safe=is_safe,
                has_real_feedback=self.has_real_feedback,
                is_ros_connected=self.is_ros_connected,
            )
